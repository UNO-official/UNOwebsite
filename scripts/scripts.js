// STRICT SECTION SCROLL LOCK ENGINE
const sections = Array.from(document.querySelectorAll('main > section'));
const VH_UNIT = (window.CSS && CSS.supports('height', '100dvh')) ? 'dvh' : 'vh';
let currentSectionIndex = 0;
let isScrolling = false;

function updateSectionTheme(index) {
    const targetSec = sections[index];
    const theme = targetSec.getAttribute('data-theme-trigger');
    const canvasContainer = document.getElementById('canvas-container');
    
    if (theme === 'light') {
        document.body.classList.remove('bg-black', 'text-silver-100', 'dark');
        document.body.classList.add('bg-silver-50', 'text-black', 'light');
        canvasContainer.style.opacity = '0.12';
    } else {
        document.body.classList.remove('bg-silver-50', 'text-black', 'light');
        document.body.classList.add('bg-black', 'text-silver-100', 'dark');
        canvasContainer.style.opacity = '0.5';
    }
}

function goToSection(index) {
    if (index < 0 || index >= sections.length) return;
    isScrolling = true;
    currentSectionIndex = index;

    const mainContainer = document.getElementById('section-container');
    mainContainer.style.transform = `translateY(-${currentSectionIndex * 100}${VH_UNIT})`;

    updateSectionTheme(currentSectionIndex);

    setTimeout(() => {
        isScrolling = false;
    }, 800);
}

// Wheel Event Scroll Lock Interceptor
window.addEventListener('wheel', (e) => {
    e.preventDefault();
    if (isScrolling) return;

    if (e.deltaY > 20) {
        goToSection(currentSectionIndex + 1);
    } else if (e.deltaY < -20) {
        goToSection(currentSectionIndex - 1);
    }
}, { passive: false });

// Keyboard Arrow Navigation
window.addEventListener('keydown', (e) => {
    if (isScrolling) return;
    if (e.key === 'ArrowDown' || e.key === 'PageDown') {
        goToSection(currentSectionIndex + 1);
    } else if (e.key === 'ArrowUp' || e.key === 'PageUp') {
        goToSection(currentSectionIndex - 1);
    }
});

// Touch Swipe Navigation for Mobile
let touchStartY = 0, touchStartX = 0;
window.addEventListener('touchstart', (e) => {
    touchStartY = e.touches[0].clientY;
    touchStartX = e.touches[0].clientX;
}, { passive: true });

window.addEventListener('touchend', (e) => {
    if (isScrolling) return;
    const diffY = touchStartY - e.changedTouches[0].clientY;
    const diffX = touchStartX - e.changedTouches[0].clientX;
    if (Math.abs(diffY) < 50 || Math.abs(diffY) < Math.abs(diffX) * 1.2) return;

    if (diffY > 0) {
        goToSection(currentSectionIndex + 1);
    } else {
        goToSection(currentSectionIndex - 1);
    }
}, { passive: true });

// Releases carousel pagination dots (mobile)
(function initReleasesDots() {
    const track = document.getElementById('releases-track');
    const dotsWrap = document.getElementById('releases-dots');
    if (!track || !dotsWrap) return;
    const cards = Array.from(track.children);
    const dots = cards.map((_, i) => {
        const b = document.createElement('button');
        b.type = 'button';
        b.setAttribute('aria-label', 'Release ' + (i + 1));
        b.className = 'h-1.5 rounded-none bg-current transition-all duration-300';
        b.addEventListener('click', () => track.scrollTo({ left: cards[i].offsetLeft, behavior: 'smooth' }));
        dotsWrap.appendChild(b);
        return b;
    });
    function update() {
        let active = 0, best = Infinity;
        cards.forEach((c, i) => {
            const d = Math.abs(c.offsetLeft - track.scrollLeft);
            if (d < best) { best = d; active = i; }
        });
        dots.forEach((b, i) => {
            b.style.width = i === active ? '1.5rem' : '0.375rem';
            b.style.opacity = i === active ? '0.9' : '0.3';
        });
    }
    track.addEventListener('scroll', update, { passive: true });
    window.addEventListener('resize', update);
    update();
})();

